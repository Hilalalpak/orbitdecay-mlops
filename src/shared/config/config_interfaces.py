    def get_mlflow_tracking_uri(self) -> str: ...
    def get_default_model_registry_name(self) -> str: ...
    def is_orbital_features_enabled(self) -> bool: ...
    def get_mlflow_experiment_name(self) -> str: ...
    def get_lstm_params(self) -> Dict[str, Any]: ...
    def get_mlflow_production_run_id(self) -> str: ...
    def get_risk_score_thresholds(self) -> Dict[str, float]: ...


