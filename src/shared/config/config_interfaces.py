"""
Lightweight protocol interfaces describing the expected behavior of all
configuration models. These are used for dependency injection and to keep
higher-level components independent from concrete config implementations.
"""

from typing import Protocol, List, Dict, Union, Any, Optional


# Storage Config Interface

class StorageConfigInterface(Protocol):
    def get_s3_endpoint(self) -> str: ...
    def get_s3_access_key(self) -> str: ...
    def get_s3_secret_key(self) -> str: ...


# Domain Config Interface

class DomainConfigInterface(Protocol):
    def get_earth_equatorial_radius_km(self) -> float: ...
    def get_earth_gravitational_parameter(self) -> float: ...
    def get_risk_thresholds(self) -> Dict[str, float]: ...


# Catalog Config Interface

class CatalogConfigInterface(Protocol):
    def get_dynamic_selection_seed(self) -> int: ...
    def get_calibration_count(self) -> int: ...
    def get_calibration_query(self) -> str: ...
    def get_target_count(self) -> int: ...
    def get_target_query(self) -> str: ...
    def get_min_orbit_days(self) -> int: ...
    def get_anchor_calibration_ids(self) -> List[str]: ...
    def get_solar_cycle_regimes(self) -> Dict[str, List[List[int]]]: ...
    def get_calibration_period_bands(self) -> Dict[str, int]: ...


# Processing Config Interface

class ProcessingConfigInterface(Protocol):
    def get_max_workers(self) -> int: ...
    def get_batch_limits(self) -> Dict[str, Any]: ...
    def get_numeric_omm_fields(self) -> List[str]: ...
    def get_critical_columns(self) -> List[str]: ...
    def get_angular_columns(self) -> List[str]: ...
    def get_sentinel_values(self) -> List[str]: ...
    def get_static_columns_to_keep(self) -> List[str]: ...
    def filter_tba_objects(self) -> bool: ...
    def get_date_range(self) -> Dict[str, str]: ...
    def is_quality_check_enabled(self) -> bool: ...
    def get_min_data_points(self) -> int: ...
    def get_max_gap_days(self) -> int: ...
    def is_orbit_classification_enabled(self) -> bool: ...
    def is_position_calculation_enabled(self) -> bool: ...
    def get_orbital_cleaning_config(self) -> Dict[str, Dict[str, Any]]: ...
    def get_orbital_segmentation_config(self) -> Dict[str, Dict[str, float]]: ...
    def get_segment_filter_config(self) -> Dict[str, Dict[str, Any]]: ...
    def get_orbital_propagation_config(self) -> Dict[str, Dict[str, Any]]: ...
    def get_far_from_tle_minutes(self) -> int: ...


# Scheduling Config Interface

class SchedulingConfigInterface(Protocol):
    def is_model_training_enabled(self) -> bool: ...
    def get_daily_reports_schedule(self) -> str: ...


# Logging Config Interface

class LoggingConfigInterface(Protocol):
    def get_log_level(self) -> str: ...
    def get_log_files(self) -> Dict[str, str]: ...
    def get_environment_name(self) -> str: ...


# Machine Learning Config Interface

